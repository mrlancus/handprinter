def _term(coef: int, v: str) -> str:
    """ ' + 3x', ' - x', or '' for a middle term."""
    if coef == 0:
        return ""
    size = "" if abs(coef) == 1 else str(abs(coef))
    return f" {'+' if coef > 0 else '-'} {size}{v}"


